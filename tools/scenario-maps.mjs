#!/usr/bin/env node
/* THE PROLOGUE'S MAPS (js/scenarios.js): the authored worlds are JSON —
   tools/scenarios/<id>.json, one per map (the format is in js/scenarios.js's
   header) — compiled here into js/scenario-maps.js, so the game reads them
   with no fetch. Edit the JSON and run:  node tools/scenario-maps.mjs
   Checks each map's shape first (38 rows of 38, a void rim, known
   characters, marks on the board) and refuses to write a broken one. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = process.argv[2] ? path.resolve(process.argv[2]) : path.join(ROOT, 'tools', 'scenarios');
const OUT = path.join(ROOT, 'js', 'scenario-maps.js');
const CHARS = new Set('#.T~rb^g,:_x'.split(''));
const KEEP = ['title', 'seed', 'region', 'landform', 'variant', 'rows', 'hall', 'rival', 'reveal', 'units', 'animals', 'buildings', 'ruins', 'relic', 'camera', 'glideFrom', 'marks'];

const maps = {};
const errs = [];
for (const f of fs.readdirSync(SRC).filter(f => /^prologue_\d\.json$/.test(f)).sort()) {
  const j = JSON.parse(fs.readFileSync(path.join(SRC, f), 'utf8'));
  const id = f.replace(/\.json$/, '');
  const bad = m => errs.push(`${f}: ${m}`);
  if (!Array.isArray(j.rows) || j.rows.length !== 38) bad('needs 38 rows');
  (j.rows || []).forEach((r, y) => {
    if (r.length !== 38) bad(`row ${y} is ${r.length} wide`);
    for (let x = 0; x < r.length; x++) {
      if (!CHARS.has(r[x])) bad(`unknown '${r[x]}' at ${x},${y}`);
      const rim = x === 0 || y === 0 || x === 37 || y === 37;
      if (rim !== (r[x] === '#')) bad(`rim/void mismatch at ${x},${y}`);
    }
  });
  const on = (x, y) => x >= 1 && y >= 1 && x <= 36 && y <= 36;
  if (!j.hall || !on(j.hall.x, j.hall.y)) bad('hall off the board');
  for (const [k, v] of Object.entries(j.marks || {})) if (!Array.isArray(v) || !on(v[0], v[1])) bad(`mark ${k} off the board`);
  const out = {};
  for (const k of KEEP) if (j[k] !== undefined) out[k] = j[k];
  maps[id] = out;
}
if (errs.length) { console.error(errs.join('\n')); process.exit(1); }
const body = `"use strict";
/* THE PROLOGUE'S MAPS — GENERATED by tools/scenario-maps.mjs from
   tools/scenarios/*.json. Do not edit by hand: edit the JSON and rebuild.
   The format is described at the top of js/scenarios.js. */
const SCENARIO_MAPS = ${JSON.stringify(maps, null, 1).replace(/\[\n\s+(-?\d+),\n\s+(-?\d+)\n\s+\]/g, '[$1, $2]')};
window.SCENARIO_MAPS = SCENARIO_MAPS;
`;
fs.writeFileSync(OUT, body);
console.log(`wrote ${path.relative(ROOT, OUT)}: ${Object.keys(maps).join(', ') || '(none)'}`);
